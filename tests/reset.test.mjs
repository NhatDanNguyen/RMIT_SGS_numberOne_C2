import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createStore } from '../server/store.mjs';
import { resetDemo } from '../scripts/reset.mjs';

test('demo reset backs up data, preserves policy and replay history, and can explicitly remove policies', () => {
  mkdirSync('.local', { recursive: true });
  const directory = mkdtempSync('.local/test-reset-');
  const path = join(directory, 'demo.sqlite');
  let store = createStore(path);
  store.saveQuote('design', 'synthetic-ciphertext', 'string', 0, 'supplier');
  store.savePolicy('design', 'synthetic-policy', 'admin');
  store.claimProof('keep-proof', Date.now() + 60000);
  store.request('design', 'buyer', 'Buyer', 'Review quote');
  store.event('buyer', 'Requested access');
  store.close();
  const result = resetDemo(path);
  assert.equal(result.reset, true);
  const backup = new DatabaseSync(result.backup, { readOnly: true });
  assert.equal(backup.prepare('SELECT ciphertext FROM quotes').get().ciphertext, 'synthetic-ciphertext');
  backup.close();
  store = createStore(path);
  assert.equal(store.quote('design'), undefined);
  assert.equal(store.requests().length, 0);
  assert.equal(store.events().length, 0);
  assert.equal(store.policy('design').policy, 'synthetic-policy');
  assert.equal(store.claimProof('keep-proof', Date.now() + 60000), false);
  store.close();
  resetDemo(path, { policies: true });
  store = createStore(path);
  assert.equal(store.policy('design'), undefined);
  store.close();
});
test('reset refuses databases outside the dedicated local demo directory', () => {
  assert.throws(() => resetDemo('../unrelated.sqlite'), /limited/);
  assert.throws(() => resetDemo('.local-other/unrelated.sqlite'), /limited/);
});
test('simulation reset clears mock grants without altering a separate live database', () => {
  mkdirSync('.local', { recursive: true });
  const directory = mkdtempSync('.local/test-isolated-reset-');
  const livePath = join(directory, 'live.sqlite'), simulatedPath = join(directory, 'simulation.sqlite');
  let live = createStore(livePath);
  live.saveQuote('design', 'live-store-must-be-preserved', 'string', 0, 'supplier');
  live.close();
  const simulated = createStore(simulatedPath);
  simulated.db.exec("CREATE TABLE simulation_grants (recipient TEXT, supplier TEXT); INSERT INTO simulation_grants VALUES ('demo-buyer','design'); CREATE TABLE simulation_changes (id TEXT); INSERT INTO simulation_changes VALUES ('request'); CREATE TABLE simulation_approvals (actor TEXT); INSERT INTO simulation_approvals VALUES ('admin');");
  simulated.close();
  resetDemo(simulatedPath, { simulation: true });
  const inspected = new DatabaseSync(simulatedPath);
  assert.equal(inspected.prepare('SELECT count(*) AS count FROM simulation_grants').get().count, 0);
  assert.equal(inspected.prepare('SELECT count(*) AS count FROM simulation_changes').get().count, 0);
  assert.equal(inspected.prepare('SELECT count(*) AS count FROM simulation_approvals').get().count, 0);
  inspected.close();
  live = createStore(livePath);
  assert.equal(live.quote('design').ciphertext, 'live-store-must-be-preserved');
  live.close();
});
